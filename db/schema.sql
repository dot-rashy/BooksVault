
-- BooksVault: Bookshop Management System
-- Database: bookshop_db
-- Run this script inside bookshop_db using pgAdmin.

CREATE SCHEMA IF NOT EXISTS bookshop;

-- 1. Customers
CREATE TABLE IF NOT EXISTS bookshop.customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cust_name VARCHAR(100) NOT NULL,
    cust_phone VARCHAR(20),
    cust_email VARCHAR(150) UNIQUE,
    cust_addr TEXT
);

-- 2. Dealers / Suppliers
CREATE TABLE IF NOT EXISTS bookshop.dealer (
    dealer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deal_name VARCHAR(150) NOT NULL,
    deal_phone VARCHAR(20),
    deal_email VARCHAR(150),
    deal_addr TEXT
);

-- 3. Books inventory
CREATE TABLE IF NOT EXISTS bookshop.book (
    isbn_id BIGINT PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    genre VARCHAR(80),
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    author_nm VARCHAR(150),
    publisher_nm VARCHAR(150)
);

-- 4. Books supplied by dealers
CREATE TABLE IF NOT EXISTS bookshop.book_supplier (
    isbn_id BIGINT NOT NULL
        REFERENCES bookshop.book(isbn_id),
    dealer_id INTEGER NOT NULL
        REFERENCES bookshop.dealer(dealer_id),
    PRIMARY KEY (isbn_id, dealer_id)
);

-- 5. Customer orders
CREATE TABLE IF NOT EXISTS bookshop.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL
        REFERENCES bookshop.customer(customer_id),
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Books belonging to each order
CREATE TABLE IF NOT EXISTS bookshop.order_books (
    order_id INTEGER NOT NULL
        REFERENCES bookshop.orders(order_id),
    isbn_id BIGINT NOT NULL
        REFERENCES bookshop.book(isbn_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, isbn_id)
);

-- Helpful indexes for common lookups
CREATE INDEX IF NOT EXISTS idx_orders_customer
    ON bookshop.orders(customer_id);

CREATE INDEX IF NOT EXISTS idx_order_books_isbn
    ON bookshop.order_books(isbn_id);

CREATE INDEX IF NOT EXISTS idx_book_title
    ON bookshop.book(title);

CREATE INDEX IF NOT EXISTS idx_book_author
    ON bookshop.book(author_nm);
